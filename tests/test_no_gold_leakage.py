"""Guard: gold must never reach the agent-visible task directory.

RCV-Bench v1 shipped curator notes as `tasks/<id>/README.md`, and
`harness/run.py::sanitized_task()` copies that file into the directory the agent
reads. Nine of fourteen notes named their own gold verdict, and several printed
the gold regenerated values. A policy that only greps that README scored
14/14 verdict accuracy and 1.000 macro-F1 with no verification of any kind.

Curator prose now lives in `GOLD/CURATOR_NOTES.md`; the agent-visible README is
generated by `harness/task_readme.agent_readme`. These tests keep it that way.
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "harness"))

from run import sanitized_task  # noqa: E402
from task_readme import VERDICT_CLASSES  # noqa: E402

TASK_DIRS = sorted(p for p in (ROOT / "tasks").iterdir() if p.is_dir())
FLOOR_CORRECT = 5  # always-REPRODUCED: 5/14


def _tokens(text):
    return sorted({c for c in VERDICT_CLASSES if c in text})


def test_tasks_exist():
    assert len(TASK_DIRS) == 14


def test_agent_readme_names_no_verdict_class():
    offenders = {
        d.name: _tokens((d / "README.md").read_text(encoding="utf-8"))
        for d in TASK_DIRS
        if (d / "README.md").is_file() and _tokens((d / "README.md").read_text(encoding="utf-8"))
    }
    assert not offenders, f"agent-visible README names verdict classes: {offenders}"


def test_curator_notes_are_on_the_gold_side():
    for d in TASK_DIRS:
        assert (d / "GOLD" / "CURATOR_NOTES.md").is_file(), f"{d.name}: curator notes missing"


def test_sanitized_dir_ships_no_gold():
    with tempfile.TemporaryDirectory() as tmp:
        for d in TASK_DIRS:
            claim = sanitized_task(str(d / "claim.json"), tmp)
            shipped = Path(claim["task_dir"])
            assert not (shipped / "GOLD").exists(), f"{d.name}: GOLD/ copied into agent dir"
            for f in shipped.rglob("*"):
                if not f.is_file():
                    continue
                text = f.read_text(encoding="utf-8", errors="replace")
                # claim.json legitimately carries task_type, which may be "ROBUST".
                if f.name == "claim.json":
                    text = json.dumps(
                        {k: v for k, v in json.loads(text).items() if k != "task_type"}
                    )
                assert not _tokens(text), f"{d.name}: {f.name} leaks {_tokens(text)}"


def test_readme_shortcut_cannot_beat_the_floor():
    """The probe baseline must collapse to the always-REPRODUCED floor."""
    with tempfile.TemporaryDirectory() as tmp:
        preds = os.path.join(tmp, "p.json")
        subprocess.run(
            [sys.executable, str(ROOT / "harness" / "run.py"),
             "--command", f"{sys.executable} {ROOT / 'baselines' / 'readme_verdict_shortcut.py'}",
             "--out", preds],
            cwd=ROOT, check=True, capture_output=True,
        )
        out = subprocess.run(
            [sys.executable, str(ROOT / "scoring" / "score.py"), preds, "--name", "guard"],
            cwd=ROOT, check=True, capture_output=True, text=True,
        ).stdout
    assert f"({FLOOR_CORRECT}/14)" in out, f"README shortcut beat the floor:\n{out}"
